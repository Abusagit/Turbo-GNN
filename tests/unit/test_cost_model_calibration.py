def synthesise(launch_ns: float, ns_per_node: float, ns_per_edge: float, shapes) -> list[Measurement]:
    """Measurements generated by a known cost model, so a fit can be checked against truth."""
    return [
        Measurement(
            conv="gt",
            pass_name="forward",
            head_dim=128,
            graph=f"g{index}",
            num_nodes=num_nodes,
            num_edges=num_edges,
            time_ms=(launch_ns + ns_per_node * num_nodes + ns_per_edge * num_edges) / 1e6,
        )
        for index, (num_nodes, num_edges) in enumerate(shapes)
    ]


SHAPES = [(2_708, 13_264), (19_717, 108_365), (169_343, 1_335_586), (2_449_029, 126_167_309)]


