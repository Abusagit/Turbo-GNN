def test_default_cost_model_is_degree_plus_two():
    assert CostModel().block_cost([3]) == 5
    assert CostModel().block_cost([3, 4]) == 11
    assert build_blocks([3], "light")[0].cost == 5


def test_alpha_charges_the_prologue_once_per_node():
    assert CostModel(alpha=8.0).block_cost([3]) == 11
    assert CostModel(alpha=8.0).block_cost([3, 3]) == 22


def test_beta_scales_the_neighbour_loop():
    assert CostModel(alpha=2.0, beta=3.0).block_cost([4]) == 14


def test_fractional_costs_round_to_whole_ticks_and_never_vanish():
    assert CostModel(alpha=2.4).block_cost([1]) == 3
    assert CostModel(alpha=0.1).block_cost([0]) == 1


@pytest.mark.parametrize("kwargs", [{"alpha": -1.0}, {"beta": 0.0}, {"beta": -1.0}])
def test_cost_model_rejects_impossible_parameters(kwargs):
    with pytest.raises(ValueError):
        CostModel(**kwargs)


def test_lpt_balances_on_cost_not_on_degree():
    # With a heavy prologue, four degree-1 nodes cost more together than one degree-4 node, so
    # balancing on raw degree (which puts all four in one block) is wrong.
    degrees = [4, 1, 1, 1, 1]
    by_cost = build_blocks(degrees, "light", "lpt", num_blocks=2, cost_model=CostModel(alpha=10.0))
    assert sorted(len(block.node_ids) for block in by_cost) == [2, 3]
    assert max(block.cost for block in by_cost) == 33

    by_degree = build_blocks(degrees, "light", "lpt", num_blocks=2, cost_model=CostModel(alpha=0.0))
    assert sorted(len(block.node_ids) for block in by_degree) == [1, 4]


def test_calibrated_tick_turns_the_makespan_into_milliseconds():
    result = simulate(
        {"light": build_blocks([3], "light")},
        {"light": KernelConfig("light", 1)},
        SimulationConfig(num_sms=1, ns_per_tick=2.0),
    )
    assert result.makespan == 5
    assert result.predicted_ms == pytest.approx(5 * 2.0 / 1e6)
    assert result.summary()["predicted_ms"] == pytest.approx(5 * 2.0 / 1e6)


def test_uncalibrated_simulation_reports_no_wall_clock():
    result = simulate(
        {"light": build_blocks([3], "light")},
        {"light": KernelConfig("light", 1)},
        SimulationConfig(num_sms=1),
    )
    assert result.predicted_ms is None


