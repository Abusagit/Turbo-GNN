def test_fit_recovers_known_coefficients():
    fit = fit_cost_model(synthesise(30_000.0, 2.4, 0.4, SHAPES))
    assert fit.ns_per_tick == pytest.approx(0.4, rel=1e-6)
    assert fit.alpha == pytest.approx(6.0, rel=1e-6)
    assert fit.beta == 1.0
    assert fit.launch_overhead_ns == pytest.approx(30_000.0, rel=1e-6)
    assert fit.r2 == pytest.approx(1.0)
    assert fit.note == ""


def test_launch_overhead_is_separated_from_the_per_node_cost():
    # Overhead dominates the small graphs; charging it to alpha is what inflates the fit.
    measurements = synthesise(200_000.0, 10.0, 0.5, SHAPES)
    corrected = fit_cost_model(measurements)
    absorbed = fit_cost_model(measurements, fit_launch_overhead=False)
    assert corrected.alpha == pytest.approx(20.0, rel=1e-6)
    assert corrected.median_rel_error < 1e-9
    assert absorbed.alpha > 1.5 * corrected.alpha
    assert absorbed.median_rel_error > 0.05


def test_relative_weighting_is_not_dominated_by_the_largest_graph():
    measurements = synthesise(5_000.0, 30.0, 0.5, SHAPES)
    perturbed = [
        Measurement(**{**m.__dict__, "time_ms": m.time_ms * (1.5 if m.num_edges == 126_167_309 else 1.0)})
        for m in measurements
    ]
    relative = fit_cost_model(perturbed, "relative")
    uniform = fit_cost_model(perturbed, "uniform")
    assert relative.median_rel_error < uniform.median_rel_error
    assert max(error for _, error in uniform.worst_graphs) > max(error for _, error in relative.worst_graphs)


def test_coefficients_are_never_negative():
    # Adding nodes at a fixed edge count makes these launches *faster*, so an unconstrained fit
    # wants a negative per-node cost. Clamping it is what keeps alpha interpretable.
    shapes_and_times = [(1_000, 1_000, 0.100), (2_000, 1_000, 0.090), (1_000, 2_000, 0.200), (2_000, 2_000, 0.190)]
    measurements = [
        Measurement("gt", "forward", 128, f"g{i}", num_nodes=n, num_edges=e, time_ms=t)
        for i, (n, e, t) in enumerate(shapes_and_times)
    ]
    fit = fit_cost_model(measurements)
    assert fit.ns_per_node == 0.0
    assert fit.ns_per_edge > 0
    assert fit.alpha == 0.0
    assert "pinned to zero" in fit.note


def test_node_dominated_kernel_is_flagged_rather_than_calibrated():
    # min-aggregation's backward pass writes one gradient per node, so its time barely moves
    # with edge count and no alpha + beta * degree model describes it.
    fit = fit_cost_model(synthesise(5_000.0, 100.0, 0.001, SHAPES))
    assert fit.edge_time_share < 0.2
    assert not fit.trustworthy
    assert "node-dominated" in fit.note


def test_fit_needs_enough_measurements_for_its_coefficients():
    with pytest.raises(ValueError, match="need at least 3"):
        fit_cost_model(synthesise(0.0, 10.0, 0.5, SHAPES[:2]))


def test_fit_rejects_non_positive_times():
    measurements = synthesise(0.0, 10.0, 0.5, SHAPES)
    broken = [Measurement(**{**measurements[0].__dict__, "time_ms": 0.0}), *measurements[1:]]
    with pytest.raises(ValueError, match="positive"):
        fit_cost_model(broken)


def test_fit_all_groups_by_conv_pass_and_head_dim():
    measurements = synthesise(0.0, 10.0, 0.5, SHAPES)
    measurements += [Measurement(**{**m.__dict__, "conv": "gat_v2"}) for m in measurements]
    measurements += [Measurement(**{**m.__dict__, "head_dim": 256, "conv": "gt"}) for m in measurements[:2]]
    fits, skipped = fit_all(measurements)
    assert set(fits) == {"gt/forward/128", "gat_v2/forward/128"}
    assert "gt/forward/256" in skipped


