#!/usr/bin/env python3
"""Five-panel occupancy heatmaps as paper figures.

One PDF per setup: the five scheduling configurations stacked on a shared time axis, styled
like the two-panel figure.  The figures carry no text beyond their axes and the panel letters
(a)...(e); the graph's shape and every panel's T/T* are printed to stdout, ready to be worked
into a caption.

    python scripts/ablation/plot_heatmap_grid.py \\
        --setups tolokers-2:gat_v2:forward:128:0.99 ogbn-arxiv:gat_v2:forward:128:0.99 \\
        --cost-model cost_models.json --sms 108 --memory-bandwidth-gbps 2039 \\
        --out-dir reports/figures

--tex additionally writes the LaTeX: a legend mapping the letters to configurations, the
definition of T/T*, and a captioned figure environment per setup.  Off unless asked for.
"""

